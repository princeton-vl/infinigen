@pf.nodes.node_function
def color_offset(
    base_color: t.SocketOrVal[pf.Color] = (0.8, 0.8, 0.8),
    hue_offset: t.SocketOrVal[float] = 0.0,
    saturation: t.SocketOrVal[float] = 1.0,
    value: t.SocketOrVal[float] = 1.0,
) -> ColorOffsetResult:
    # Code generated by procfunc v0.34.0
    offset_color_hue = hue_offset + 1.0

    offset_color = pf.nodes.color.hue_saturation(
        color=base_color,
        fac=1.0,
        hue=offset_color_hue / 2.0,
        saturation=saturation,
        value=value,
    )
    return ColorOffsetResult(base_color, offset_color)


@pf.nodes.node_function
def _colorize(
    map: t.SocketOrVal[float] = 0.5,
    color_1: t.SocketOrVal[pf.Color] = (0.204908, 0.124432, 0.074749),
    color_2: t.SocketOrVal[pf.Color] = (0.116264, 0.041582, 0.022454),
    contrast: t.SocketOrVal[float] = 0.0,
    variation_by_id: t.SocketOrVal[float] = 0.0,
    id: t.SocketOrVal[pf.Vector] = (0.0, 0.0, 0.0),
) -> pf.ProcNode[pf.Color]:
    # Code generated by procfunc v0.34.0
    result_0_a_1 = pf.nodes.math.absolute(contrast)

    result_0_a_factor_b = result_0_a_1 + 1.0
    result_0_a_factor_0 = pf.nodes.math.mix(
        a=1.0 / result_0_a_factor_b,
        b=result_0_a_factor_b,
        factor=contrast > 0.0,
        data_type=NodeDataType.FLOAT,
    )
    result_0_a_0 = pf.nodes.color.mix_rgb(
        factor=map**result_0_a_factor_0, a=color_1, b=color_2
    )
    result_0_b = pf.nodes.texture.white_noise(vector=id, noise_dimensions="4D", w=0.0)
    mix_rgb = pf.nodes.color.mix_rgb(
        factor=variation_by_id,
        a=result_0_a_0,
        b=result_0_b.fac.astype(dtype=pf.Color),
        blend_type="SOFT_LIGHT",
    )

    return mix_rgb


class LeatherShaderResult(NamedTuple):
    bsdf: pf.ProcNode[pf.Shader]
    displacement: pf.ProcNode[pf.Vector]
    tmp_viewer: pf.ProcNode[pf.Shader]


@pf.nodes.node_function
def leather_shader(
    cells: t.SocketOrVal[float] = 0.5,
    contrast: t.SocketOrVal[float] = 0.0,
    base_color: t.SocketOrVal[pf.Color] = (0.082627, 0.020573, 0.004636),
    base_roughness: t.SocketOrVal[float] = 0.4,
    base_specular: t.SocketOrVal[float] = 0.17727272,
    crease_color: t.SocketOrVal[pf.Color] = (0.17653237, 0.070236385, 0.009860594),
    crease_roughness: t.SocketOrVal[float] = 0.6,
    crease_specular: t.SocketOrVal[float] = 0.1,
    cell_height: t.SocketOrVal[float] = 0.001,
    per_cell_variation: t.SocketOrVal[float] = 0.0,
    cell_id: t.SocketOrVal[pf.Vector] = (0.0, 0.0, 0.0),
) -> LeatherShaderResult:
    # Code generated by procfunc v0.34.0
    colorize_result = _colorize(
        map=cells,
        color_1=crease_color,
        color_2=base_color,
        contrast=contrast,
        variation_by_id=per_cell_variation,
        id=cell_id,
    )

    principled = pf.nodes.shader.principled_bsdf(
        base_color=colorize_result,
        roughness=base_roughness,
        subsurface_radius=(1.0, 0.2, 0.1),
        subsurface_anisotropy=0.0,
        specular_ior_level=base_specular,
    )

    displacement = pf.nodes.shader.displacement(
        height=cells, midlevel=0.0, scale=cell_height
    )

    return LeatherShaderResult(principled, displacement, principled)


class GrungeResult(NamedTuple):
    vector: t.SocketOrVal[pf.Vector]
    color: pf.ProcNode[pf.Color]
    texture: pf.ProcNode[float]
    mask: t.SocketOrVal[float]


@pf.nodes.node_function
def grunge(
    vector: t.SocketOrVal[pf.Vector] = (-999999.0, -999999.0, -999999.0),
    base_color: t.SocketOrVal[pf.Color] = (0.5, 0.5, 0.5),
    grunge_color: t.SocketOrVal[pf.Color] = (0.5, 0.5, 0.5),
    mix_mode: t.SocketOrVal[float] = 1.0,
    invert: t.SocketOrVal[float] = 0.0,
    spread: t.SocketOrVal[float] = 0.5,
    smoothness: t.SocketOrVal[float] = 0.5,
    mask: t.SocketOrVal[float] = 1.0,
    seed: t.SocketOrVal[float] = 0.0,
    noise_settings_size: t.SocketOrVal[float] = 0.25,
    noise_settings_detail: t.SocketOrVal[float] = 4.0,
    noise_settings_roughness: t.SocketOrVal[float] = 0.5,
    distortion_strength: t.SocketOrVal[float] = 9.339999,
    distortion_size: t.SocketOrVal[float] = 0.25,
    distortion_detail: t.SocketOrVal[float] = 4.0,
    distortion_roughness: t.SocketOrVal[float] = 0.5,
) -> GrungeResult:
    # Code generated by procfunc v0.34.0
    color_factor_1 = pf.nodes.math.clamp(value=mix_mode, min=1.0, max=3.0)

    color_factor_0 = pf.nodes.math.clamp(color_factor_1 - 2.0)
    color_a_factor = pf.nodes.math.clamp(color_factor_1 - 1.0)
    space_warp_result = space_warp(
        vector=vector,
        strength=distortion_strength,
        w=seed,
        size=distortion_size,
        detail=distortion_detail,
        roughness=distortion_roughness,
    )

    texture_value_a = pf.nodes.texture.noise(
        vector=space_warp_result.vector,
        scale=1.0 / noise_settings_size,
        detail=noise_settings_detail,
        roughness=noise_settings_roughness,
        noise_dimensions="4D",
        w=seed,
    )

    texture_value = pf.nodes.math.mix(
        a=texture_value_a.fac,
        b=1.0 - texture_value_a.fac,
        factor=invert,
        data_type=NodeDataType.FLOAT,
    )
    texture_from_min = pf.nodes.math.minimum(a=1.0 - spread, b=0.99999)
    texture_from_max = pf.nodes.math.mix(
        a=texture_from_min + 1e-05,
        b=1.0,
        factor=smoothness,
        data_type=NodeDataType.FLOAT,
    )
    texture = pf.nodes.math.map_range(
        value=texture_value,
        from_max=texture_from_max,
        from_min=texture_from_min,
        to_max=mask,
        data_type=NodeDataType.FLOAT,
    )
    color_a_a = pf.nodes.color.mix_rgb(factor=texture, a=base_color, b=grunge_color)

    color_a_b = pf.nodes.color.mix_rgb(
        factor=texture,
        a=base_color,
        b=grunge_color,
        blend_type="SOFT_LIGHT",
    )
    color_a = pf.nodes.color.mix_rgb(factor=color_a_factor, a=color_a_a, b=color_a_b)
    color_b = pf.nodes.color.mix_rgb(
        factor=texture,
        a=base_color,
        b=grunge_color,
        blend_type="MULTIPLY",
    )
    color = pf.nodes.color.mix_rgb(factor=color_factor_0, a=color_a, b=color_b)
    return GrungeResult(vector, color, texture, mask)


