import math
from typing import NamedTuple

import numpy as np
import procfunc as pf
from procfunc.nodes import types as t

from infinigen2.cameras import framing
from infinigen2.curves.room_edge import (
    RoomEdgeCurveResult,
    room_edge_curve_rand,
)
from infinigen2.scenes.room.wall_base import WallSurface
from infinigen2.util.curve import curve_to_mesh_with_uv
from infinigen2.util.mesh import crease_sharp, grid_from_corners

__all__ = [
    "RoomEdgeToWallsResult",
    "RoomFloorCeilingResult",
    "RoomShapeResult",
    "room_dimensions_rand",
    "room_edge_to_walls",
    "room_floor_ceiling",
    "room_shape_rand",
]


WALL_EDGE_OVERHANG = 0.01


class RoomShapeResult(NamedTuple):
    walls: pf.MeshObject
    flat_walls: list[WallSurface]
    floor: pf.MeshObject
    ceiling: pf.MeshObject
    dimensions: pf.Vector
    edge_curve: RoomEdgeCurveResult
    all_objects: list[pf.MeshObject]
    cameras: list[pf.CameraObject]


class RoomEdgeToWallsResult(NamedTuple):
    geometry: pf.ProcNode[pf.MeshObject]
    vector: pf.ProcNode[pf.Vector]
    is_face_flat: pf.ProcNode[bool]


@pf.nodes.node_function
def room_edge_to_walls(
    curve: pf.ProcNode[pf.CurveObject],
    height: t.SocketOrVal[float],
    is_edge_point_flat: t.SocketOrVal[bool],
) -> RoomEdgeToWallsResult:
    # Code generated by procfunc v0.16.1

    curve_line_end = pf.nodes.math.vector_multiply_add(
        a=height.astype(dtype=pf.Vector),
        b=(0.0, -1.0, 0.0),
        addend=(0.0, -WALL_EDGE_OVERHANG, 0.0),
    )
    curve_line = pf.nodes.geo.curve_line(
        start=(0.0, WALL_EDGE_OVERHANG, 0.0), end=curve_line_end
    )

    input_index = pf.nodes.geo.input_index()

    capture_attribute = pf.nodes.geo.capture_attribute(
        geometry=curve_line, index=input_index
    )

    curve_to_mesh_with_uv_result = curve_to_mesh_with_uv(
        curve=pf.nodes.geo.set_curve_normal(curve, mode="Z_UP"),
        profile=capture_attribute.geometry,
    )

    capture_attribute_1 = pf.nodes.geo.capture_attribute(
        geometry=curve_to_mesh_with_uv_result.mesh,
        domain="FACE",
        value=is_edge_point_flat,
    )

    input_edge_angle = pf.nodes.geo.input_mesh_edge_angle()

    geometry_b = pf.nodes.math.deg_to_rad(20.0)
    geometry_value_a_a = pf.nodes.func.greater_than(
        a=input_edge_angle.unsigned_angle, b=geometry_b
    )
    geometry_value = pf.nodes.func.boolean_or(
        a=geometry_value_a_a, b=capture_attribute_1.value
    )

    store_named_attribute = pf.nodes.geo.store_named_attribute(
        geometry=capture_attribute_1.geometry,
        name="crease_edge",
        value=geometry_value.astype(dtype=float),
        domain="EDGE",
    )
    return RoomEdgeToWallsResult(
        geometry=store_named_attribute,
        vector=curve_to_mesh_with_uv_result.vector,
        is_face_flat=capture_attribute_1.value,
    )


@pf.tracer.grammar
def room_dimensions_rand(
    rng: pf.RNG,
) -> pf.Vector:
    width = pf.random.clip_gaussian(rng, 4.5, 1, 3.5, 8)
    depth = pf.random.clip_gaussian(rng, 5.5, 1, 4.5, 8)
    height = pf.random.clip_gaussian(rng, 2.5, 1, 2.2, 4.5)
    dimensions = pf.Vector((width, depth, height))
    return dimensions


class RoomFloorCeilingResult(NamedTuple):
    floor: pf.MeshObject
    ceiling: pf.MeshObject


@pf.tracer.generator
def room_floor_ceiling(
    width: float, depth: float, height: float, offset_epsilon: float
) -> RoomFloorCeilingResult:
    vertices_x = math.ceil(width / 0.8) + 1
    vertices_y = math.ceil(depth / 0.8) + 1
    floor = grid_from_corners(
        point_1=(0, 0, -offset_epsilon),
        point_2=(width, depth, -offset_epsilon),
        vertices_x=vertices_x,
        vertices_y=vertices_y,
    )
    ceiling = grid_from_corners(
        point_1=(0, 0, height + offset_epsilon),
        point_2=(width, depth, height + offset_epsilon),
        vertices_x=vertices_x,
        vertices_y=vertices_y,
    )
    floor_obj = pf.nodes.to_mesh_object(floor)
    ceiling_obj = pf.nodes.to_mesh_object(pf.nodes.geo.flip_faces(ceiling))
    pf.ops.attr.write_attribute(floor_obj, 1.0, "crease_edge", domain="EDGE")
    pf.ops.attr.write_attribute(ceiling_obj, 1.0, "crease_edge", domain="EDGE")
    pf.ops.uv.cube_project(ceiling_obj, uv_name="UVMap")
    return RoomFloorCeilingResult(floor=floor_obj, ceiling=ceiling_obj)


def _split_flat_walls(
    walls_mesh: pf.MeshObject, wall_lengths: list[float], height: float
) -> list[WallSurface]:
    wall_idx = pf.ops.attr.read_attribute(walls_mesh, "wall_idx", domain="FACE")
    uniq_idx = np.unique(wall_idx)

    results = []
    for idx in uniq_idx:
        wall_idx = pf.ops.attr.read_attribute(walls_mesh, "wall_idx", domain="FACE")
        is_wall_flat = pf.ops.attr.read_attribute(
            walls_mesh, "is_wall_flat", domain="FACE"
        )
        mask = (wall_idx == idx) * is_wall_flat
        if not mask.any():
            continue
        wall = pf.ops.mesh.separate_mask(walls_mesh, face_mask=mask)
        surface_height = height + 2 * WALL_EDGE_OVERHANG
        results.append(WallSurface(wall, wall_lengths[int(idx)], surface_height))

    return results


@pf.tracer.grammar
def room_shape_rand(
    rng: pf.RNG,
    dimensions: pf.Vector | None = None,
    floor_ceiling_offset_epsilon: float = 0.005,
) -> RoomShapeResult:
    if dimensions is None:
        dimensions = room_dimensions_rand(rng)

    edge_curve = room_edge_curve_rand(rng, dimensions=dimensions)

    walls = room_edge_to_walls(
        curve=edge_curve.curve,
        height=dimensions.z,
        is_edge_point_flat=edge_curve.is_flat_point,
    )
    geo = walls.geometry
    geo = pf.nodes.geo.store_named_attribute(
        geometry=geo,
        name="wall_idx",
        value=edge_curve.orig_point_idx,
        domain="FACE",
    )
    geo = pf.nodes.geo.store_named_attribute(
        geometry=geo,
        name="is_wall_flat",
        value=walls.is_face_flat,
        domain="FACE",
    )
    geo = pf.nodes.geo.merge_by_distance(geo, distance=0.001)

    geo = crease_sharp(geo, threshold_degrees=20.0)

    # crease top/bottom edges (edge_neighbors == 1 means boundary edge)
    edge_neighbors = pf.nodes.geo.input_mesh_edge_neighbors()
    is_boundary_edge = pf.nodes.func.equal(a=edge_neighbors, b=1)
    geo = pf.nodes.geo.store_named_attribute(
        geometry=geo,
        name="crease_edge",
        value=1.0,
        domain="EDGE",
        selection=is_boundary_edge,
    )

    # needed for when we split the walls
    geo = pf.nodes.geo.store_named_attribute(
        geometry=geo,
        name="crease_edge",
        value=1.0,
        domain="EDGE",
        selection=walls.is_face_flat,
    )

    walls_mesh = pf.nodes.to_mesh_object(geo)

    floor_ceiling = room_floor_ceiling(
        float(dimensions.x),
        float(dimensions.y),
        float(dimensions.z),
        floor_ceiling_offset_epsilon,
    )
    floor = floor_ceiling.floor
    ceiling = floor_ceiling.ceiling

    flat_walls = _split_flat_walls(
        walls_mesh, edge_curve.wall_lengths, float(dimensions.z)
    )
    camera = framing.camera_in_room_corner(floor, float(dimensions.z))

    for obj in [walls_mesh, floor, ceiling] + [w.obj for w in flat_walls]:
        obj.item().name = "room_shape"

    return RoomShapeResult(
        walls=walls_mesh,
        flat_walls=flat_walls,
        floor=floor,
        ceiling=ceiling,
        dimensions=dimensions,
        edge_curve=edge_curve,
        all_objects=[walls_mesh, *[w.obj for w in flat_walls], floor, ceiling],
        cameras=[camera],
    )
